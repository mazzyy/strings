import { chromium } from "playwright-core";
import fs from "node:fs";
const out = process.argv[2];
const base = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64`;
const exe = fs.readdirSync(base).find(f => f.endsWith(".app"));
const browser = await chromium.launch({ executablePath: `${base}/${exe}/Contents/MacOS/${exe.replace(".app","")}`, args: ["--use-angle=swiftshader","--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const logs = [];
page.on("pageerror", e => logs.push("pageerror " + e.message));
await page.addInitScript(() => localStorage.clear());
await page.goto("http://localhost:8095/?emulate");
await page.waitForSelector("#begin", { timeout: 60000 });
await page.evaluate(() => document.getElementById("enter-vr").click());
await page.waitForFunction(() => window.strings?.book.open, null, { timeout: 30000 }).catch(() => {});
await page.waitForTimeout(1500);
const r = await page.evaluate(() => {
  const s = window.strings, m = s.book.mesh, V = m.position.constructor;
  const n = new V(0, 0, 1).applyQuaternion(m.getWorldQuaternion(new m.quaternion.constructor()));
  const to = s.camera.getWorldPosition(new V()).sub(m.getWorldPosition(new V())).normalize();
  const before = s.book.page;
  const poked = s.book.poke(m.localToWorld(new V(0, 0, 0.005)));
  return { open: s.book.open, visible: m.visible, facing: +n.dot(to).toFixed(2), before, poked };
});
await page.waitForTimeout(600);
r.after = await page.evaluate(() => window.strings.book.page);
await page.screenshot({ path: `${out}/v3-book.png` });
await page.evaluate(() => window.strings.book.finish());
await page.waitForTimeout(800);
r.preshow = await page.evaluate(() => window.strings.preshow);
console.log(JSON.stringify(r), logs.join(" ") || "no errors");
await browser.close();
