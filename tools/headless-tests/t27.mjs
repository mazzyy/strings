import { chromium } from "playwright-core";
import fs from "node:fs";
const out = process.argv[2];
const base = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64`;
const exe = fs.readdirSync(base).find(f => f.endsWith(".app"));
const browser = await chromium.launch({ executablePath: `${base}/${exe}/Contents/MacOS/${exe.replace(".app","")}`, args: ["--use-angle=swiftshader","--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const logs = [];
page.on("console", m => { if (m.type() === "error" && !m.text().includes("Failed to load resource")) logs.push(m.text()); });
page.on("pageerror", e => logs.push("pageerror " + e.message + " " + (e.stack || "").split("\n")[1]));
const S = (fn, a) => page.evaluate(fn, a);
const waitFor = (fn, a, ms = 120000) => page.waitForFunction(fn, a, { timeout: ms }).catch(() => "timeout");
const st = () => S(() => { const s = window.strings; return { preshow: s.preshow, started: s.showStarted, intro: s.intro?.on, book: s.book.open, page: s.book.page, show: s.show.state, cap: document.getElementById("caption")?.textContent?.slice(0, 60) }; });
await page.addInitScript(() => localStorage.clear());
await page.goto("http://localhost:8095/");
await page.waitForSelector("#begin", { timeout: 90000 });
const t0 = Date.now();
await page.click("#begin");
await page.waitForTimeout(1500);
console.log("after begin", (Date.now() - t0) / 1000, JSON.stringify(await st()));
await page.screenshot({ path: `${out}/o1-cord.png` });
await S(() => window.strings.raiseCurtain());
await page.waitForTimeout(4000);
console.log("curtain up", JSON.stringify(await st()));
await page.screenshot({ path: `${out}/o2-warmup.png` });
// lift and move Sir Pip
await S(() => { window.strings.sim.sticky = true; });
for (let i = 0; i < 30; i++) { await S((i) => { window.strings.sim.mainPos.x = -0.16 + Math.sin(i / 4) * 0.08; window.strings.sim.mainPos.y = 0.56; }, i); await page.waitForTimeout(80); }
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/o3-hello.png` });
console.log("moved", JSON.stringify(await st()));
await waitFor(() => window.strings.book.open, null, 90000);
console.log("book", JSON.stringify(await st()));
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/o4-book.png` });
await page.click("#storybook .skip");
await waitFor(() => window.strings.show.state === "intro" || window.strings.show.state === "act", null, 30000);
console.log("after skip", JSON.stringify(await st()));
console.log(logs.slice(0, 10).join("\n") || "no errors");
await browser.close();
