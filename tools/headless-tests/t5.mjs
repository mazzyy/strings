import { chromium } from "playwright-core";
import fs from "node:fs";
const out = process.argv[2];
const base = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64`;
const exe = fs.readdirSync(base).find(f => f.endsWith(".app"));
const browser = await chromium.launch({ executablePath: `${base}/${exe}/Contents/MacOS/${exe.replace(".app","")}`, args: ["--use-angle=swiftshader","--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const logs = [];
page.on("console", m => { if (m.type() === "error" && !m.text().includes("Failed to load resource")) logs.push(m.text()); });
page.on("pageerror", e => logs.push("pageerror " + e.message));
await page.addInitScript(() => localStorage.clear());
await page.goto("http://localhost:8095/?emulate");
await page.waitForSelector("#begin", { timeout: 60000 });
await page.evaluate(() => document.getElementById("enter-vr").click());
await page.waitForTimeout(2500);
await page.evaluate(() => { const s = window.strings; s.raiseCurtain(); s.storyMap.complete("courtyard", { stars: 3 }); s.openMap(); });
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/v1-map.png` });
console.log("orient", await page.evaluate(() => { const s = window.strings, m = s.storyMap.mesh; const V = m.position.constructor; const mw = m.getWorldPosition(new V()); const n = new V(0, 0, 1).applyQuaternion(m.getWorldQuaternion(new m.quaternion.constructor())); const cam = new V().setFromMatrixPosition(s.renderer.xr.getCamera().matrixWorld); const camU = s.camera.getWorldPosition(new V()); const to = cam.clone().sub(mw).normalize(); return JSON.stringify({ mw: mw.toArray().map(v => +v.toFixed(2)), cam: cam.toArray().map(v => +v.toFixed(2)), camU: camU.toArray().map(v => +v.toFixed(2)), n: n.toArray().map(v => +v.toFixed(2)), dot: +n.dot(to).toFixed(2), rot: m.rotation.toArray().slice(0, 3).map(v => +(+v).toFixed(2)), stageRot: s.stageRoot.rotation.y.toFixed(2) }); }));
const r = await page.evaluate(() => {
  const s = window.strings, m = s.storyMap, p = m.places.find(x => x.id === "forest");
  const vx = p.map[0] - m.cam.x, vy = p.map[1] - m.cam.y;
  const world = m.mesh.localToWorld(new m.mesh.position.constructor((vx / 1200 - 0.5) * 0.4, (0.5 - vy / 750) * 0.25, 0.005));
  return { visible: m.mesh.visible, poked: m.poke(world) };
});
console.log("xr map", JSON.stringify(r));
await page.waitForFunction(() => window.strings.guestId === "wizard", null, { timeout: 120000 }).catch(() => {});
await page.waitForTimeout(4000);
console.log("after", await page.evaluate(() => ({ guest: window.strings.guestId, set: window.strings.sets.current, mapVisible: window.strings.storyMap.mesh.visible })));
await page.screenshot({ path: `${out}/v2-forest-vr.png` });
console.log("xr draw", await page.evaluate(async () => { const r = window.strings.renderer; await new Promise(res => requestAnimationFrame(res)); return r.info.render.calls; }));
console.log(logs.slice(0, 10).join("\n") || "no errors");
await browser.close();
