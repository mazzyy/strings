import { chromium } from "playwright-core";
import fs from "node:fs";
const base = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64`;
const exe = fs.readdirSync(base).find(f => f.endsWith(".app"));
const browser = await chromium.launch({ executablePath: `${base}/${exe}/Contents/MacOS/${exe.replace(".app","")}`, args: ["--use-angle=swiftshader","--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errs = [], bad = [];
page.on("pageerror", e => errs.push(e.message));
page.on("console", m => { if (m.type() === "error" && !m.text().includes("Failed to load resource")) errs.push(m.text()); });
page.on("response", r => { if (r.status() >= 400 && !r.url().includes("/api/")) bad.push(r.status() + " " + r.url()); });
const S = (fn, a) => page.evaluate(fn, a);
await page.goto("https://mazzyy.github.io/strings/");
await page.waitForSelector("#begin", { timeout: 90000 });
await page.click("#begin");
await page.waitForFunction(() => window.strings?.intro.on, null, { timeout: 20000 });
const intro = await S(() => ({ intro: window.strings.intro.on, sparkles: window.strings.sparkles.points.visible, camMoving: window.strings.camTween.on }));
await page.waitForFunction(() => window.strings.book.open, null, { timeout: 180000 });
await page.waitForTimeout(800);
await page.click("#storybook canvas");
await page.waitForFunction(() => window.strings.book.flip, null, { timeout: 20000 }).catch(() => {});
const flipped = await S(() => !!window.strings.book.flip || window.strings.book.page >= 1);
console.log(JSON.stringify({ ...intro, book: await S(() => window.strings.book.chapter.id), pageTurn: flipped, voices: await S(() => Object.keys(window.strings.narrator.manifest).length), errors: errs.slice(0, 5), failed: bad.slice(0, 5) }));
await browser.close();
