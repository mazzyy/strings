import { chromium } from "playwright-core";
import fs from "node:fs";
const out = process.argv[2];
const base = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64`;
const exe = fs.readdirSync(base).find(f => f.endsWith(".app"));
const browser = await chromium.launch({ executablePath: `${base}/${exe}/Contents/MacOS/${exe.replace(".app","")}`, args: ["--use-angle=swiftshader","--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const logs = [];
page.on("pageerror", e => logs.push("pageerror " + e.message + " " + (e.stack || "").split("\n")[1]));
page.on("console", m => { if (m.type() === "error" && !m.text().includes("Failed to load resource")) logs.push(m.text()); });
const S = (fn, a) => page.evaluate(fn, a);
const waitFor = (fn, a, ms = 120000) => page.waitForFunction(fn, a, { timeout: ms }).catch(() => "timeout");
const menuOpen = () => S(() => !document.getElementById("loading").classList.contains("done"));
await page.addInitScript(() => localStorage.clear());
await page.goto("http://localhost:8095/");
await page.waitForSelector("#freeplay", { timeout: 90000 });
// start in free play, then use the menu to get to the story
await page.click("#freeplay");
await page.waitForTimeout(1500);
console.log("free play:", await S(() => document.body.classList.contains("free-play")), "menu open:", await menuOpen());
await page.click("#menubtn");
await page.waitForTimeout(500);
console.log("☰ Menu -> open:", await menuOpen(), "buttons:", await S(() => [...document.querySelectorAll("#loading button")].map(b => b.textContent).join(" | ")));
await page.screenshot({ path: `${out}/menu1.png` });
await page.click("#backtoshow");
await page.waitForTimeout(400);
console.log("back to show -> open:", await menuOpen());
await page.keyboard.press("Escape");
await page.waitForTimeout(400);
console.log("Esc -> open:", await menuOpen());
await page.keyboard.press("Escape");
await page.waitForTimeout(400);
console.log("Esc again -> open:", await menuOpen());
await page.keyboard.press("Escape");
await page.waitForTimeout(300);
await page.click("#begin");
await waitFor(() => window.strings.book.open, null, 30000);
console.log("story from menu: free play left:", !(await S(() => document.body.classList.contains("free-play"))), "book:", await S(() => window.strings.book.open), "chapter:", await S(() => window.strings.chapter.id));
await S(() => window.strings.book.skipAll());
await waitFor(() => window.strings.show.state === "intro" || window.strings.show.state === "act", null, 60000);
// mid-story: write a story (typing letters that are shortcuts)
await page.keyboard.press("Escape");
await page.waitForTimeout(400);
await page.click("#mystory");
await page.click("#storymaker textarea");
await page.keyboard.type("a troll stole the treasure, trust me");
await page.waitForTimeout(400);
console.log("typed; recording?", await S(() => window.strings.recorder.recording), "demo?", await S(() => !!window.strings.sim.autopilot), "freed?", await S(() => window.strings.unbound.busy));
await page.click("#storymaker .go");
await waitFor(() => window.strings.book.open && window.strings.book.chapter.id === "custom", null, 30000);
console.log("custom story:", await S(() => window.strings.book.chapter.title));
console.log(logs.slice(0, 8).join("\n") || "no errors");
await browser.close();
