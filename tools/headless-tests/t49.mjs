import { chromium } from "playwright-core";
import fs from "node:fs";
const out = process.argv[2];
const base = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64`;
const exe = fs.readdirSync(base).find(f => f.endsWith(".app"));
const browser = await chromium.launch({ executablePath: `${base}/${exe}/Contents/MacOS/${exe.replace(".app","")}`, args: ["--use-angle=swiftshader","--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1400, height: 860 } });
const logs = [];
page.on("pageerror", e => logs.push("pageerror " + e.message + " " + (e.stack || "").split("\n")[1]));
const S = (fn, a) => page.evaluate(fn, a);
await page.addInitScript(() => localStorage.clear());
await page.goto("http://localhost:8095/?autostart");
await page.waitForFunction(() => window.strings?.show, null, { timeout: 60000 });
await page.waitForTimeout(4000);
console.log("draw calls:", await S(() => window.strings.renderer.info.render.calls), "visible toolbar:", await S(() => [...document.querySelectorAll("#top .buttons > *")].filter(b => b.offsetParent).map(b => b.textContent.trim()).join(" | ")));
await page.click("#menubtn");
await page.waitForTimeout(500);
console.log("menu extras:", await S(() => [...document.querySelectorAll(".extras button")].map(b => b.textContent).join(" | ")));
await page.screenshot({ path: `${out}/menu-extras.png` });
await page.click("#x-dev");
await page.waitForTimeout(300);
console.log("dev info shown:", await S(() => !!document.querySelector("#top .card").offsetParent));
console.log(logs.join("\n") || "no errors");
await browser.close();
