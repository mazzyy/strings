import { chromium } from "playwright-core";
import fs from "node:fs";
const base = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64`;
const exe = fs.readdirSync(base).find(f => f.endsWith(".app"));
const browser = await chromium.launch({ executablePath: `${base}/${exe}/Contents/MacOS/${exe.replace(".app","")}`, args: ["--use-angle=swiftshader","--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errs = [], bad = [];
page.on("pageerror", e => errs.push(e.message));
page.on("console", m => { if (m.type() === "error" && !m.text().includes("Failed to load resource")) errs.push(m.text()); });
page.on("response", r => { if (r.status() >= 400 && !r.url().includes("/api/")) bad.push(r.status() + " " + r.url()); });
await page.goto("https://mazzyy.github.io/strings/");
await page.waitForSelector("#begin", { timeout: 90000 });
await page.click("#begin");
await page.waitForFunction(() => window.strings?.hints.current === "cord", null, { timeout: 60000 });
await page.evaluate(() => window.strings.raiseCurtain());
await page.waitForFunction(() => window.strings.show.state === "intro", null, { timeout: 90000 });
const a = await page.evaluate(() => ({ chapter: window.strings.chapter.title, guest: window.strings.guestId, voices: Object.keys(window.strings.narrator.manifest).length }));
await page.evaluate(() => { const s = window.strings; s.storyMap.complete("courtyard", { stars: 3 }); s.openMap(); });
await page.waitForTimeout(1500);
await page.screenshot({ path: process.argv[2] + "/live-map.png" });
const fp = await page.evaluate(() => { const m = window.strings.storyMap; const p = m.places.find(x => x.id === "forest"); const r = m.canvas.getBoundingClientRect(); return { x: r.left + (p.map[0] - m.cam.x) / 1200 * r.width, y: r.top + (p.map[1] - m.cam.y) / 750 * r.height }; });
await page.mouse.click(fp.x, fp.y);
await page.waitForFunction(() => window.strings.guestId === "wizard" && window.strings.show.state === "intro", null, { timeout: 120000 }).catch(() => {});
await page.waitForTimeout(2000);
await page.screenshot({ path: process.argv[2] + "/live-forest.png" });
const b = await page.evaluate(() => ({ chapter: window.strings.chapter.title, guest: window.strings.guestId, set: window.strings.sets.current }));
console.log(JSON.stringify({ start: a, afterMap: b, errors: errs.slice(0, 5), failed: bad.slice(0, 5) }));
await browser.close();
