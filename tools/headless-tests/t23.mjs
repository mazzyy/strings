import { chromium } from "playwright-core";
import fs from "node:fs";
const out = process.argv[2];
const base = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64`;
const exe = fs.readdirSync(base).find(f => f.endsWith(".app"));
const browser = await chromium.launch({ executablePath: `${base}/${exe}/Contents/MacOS/${exe.replace(".app","")}`, args: ["--use-angle=swiftshader","--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
page.on("pageerror", e => console.log("pageerror", e.message));
const S = (fn, a) => page.evaluate(fn, a);
await page.addInitScript(() => localStorage.clear());
await page.goto("http://localhost:8095/");
await page.waitForSelector("#begin", { timeout: 90000 });
await page.click("#begin");
await page.waitForFunction(() => window.strings?.intro.on && window.strings.intro.t > 0.9, null, { timeout: 60000 });
await page.screenshot({ path: `${out}/i-greet.png` });
await page.waitForFunction(() => !window.strings.intro.on || window.strings.intro.t > 3.2, null, { timeout: 120000 });
await page.screenshot({ path: `${out}/i-conjure.png` });
console.log("intro t", await S(() => window.strings.intro.t.toFixed(2)));
await browser.close();
