import { chromium } from "playwright-core";
import fs from "node:fs";
const out = process.argv[2];
const base = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64`;
const exe = fs.readdirSync(base).find(f => f.endsWith(".app"));
const browser = await chromium.launch({ executablePath: `${base}/${exe}/Contents/MacOS/${exe.replace(".app","")}`, args: ["--use-angle=swiftshader","--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const logs = [];
page.on("pageerror", e => logs.push("pageerror " + e.message));
const S = (fn, a) => page.evaluate(fn, a);
const waitFor = (fn, a, ms = 120000) => page.waitForFunction(fn, a, { timeout: ms }).catch(() => "timeout");
await page.addInitScript(() => localStorage.clear());
await page.goto("http://localhost:8095/?autostart");
await waitFor(() => window.strings?.show.state === "intro");
await page.waitForTimeout(1500);
// the finale's last beat: armed, then applause (K) sets him free
let doneCalled = false;
await S(() => { const s = window.strings; s.__done = false; s.unbound.armForApplause(() => { s.__done = true; }); });
await page.keyboard.press("k");
await waitFor(() => window.strings.unbound.state === "loop", null, 60000);
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/u-desk-loop.png` });
await waitFor(() => window.strings.unbound.state === "perch", null, 120000);
await waitFor(() => window.strings.unbound.t > 2, null, 60000);
await page.screenshot({ path: `${out}/u-desk-perch.png` });
await waitFor(() => window.strings.unbound.state === "off", null, 120000);
console.log("desktop flow", await S(() => ({ done: window.strings.__done, strings: window.strings.marlo.stringLines.visible, ai: !window.strings.ai.suspended })));
console.log(logs.join("\n") || "no errors");
await browser.close();
