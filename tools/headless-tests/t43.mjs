import { chromium } from "playwright-core";
import fs from "node:fs";
const out = process.argv[2];
const base = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64`;
const exe = fs.readdirSync(base).find(f => f.endsWith(".app"));
const browser = await chromium.launch({ executablePath: `${base}/${exe}/Contents/MacOS/${exe.replace(".app","")}`, args: ["--use-angle=swiftshader","--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const logs = [];
page.on("pageerror", e => logs.push("pageerror " + e.message + " " + (e.stack || "").split("\n")[1]));
const S = (fn, a) => page.evaluate(fn, a);
const waitFor = (fn, a, ms = 120000) => page.waitForFunction(fn, a, { timeout: ms }).catch(() => "timeout");
await page.addInitScript(() => localStorage.clear());
await page.goto("http://localhost:8095/?emulate");
await page.waitForSelector("#begin", { timeout: 90000 });
await S(() => document.getElementById("enter-vr").click());
await page.waitForTimeout(3000);
await S(() => window.strings.raiseCurtain());
await page.waitForTimeout(800);
// headset menu -> Story cards
await S(() => window.strings.openGameMenu());
await page.waitForTimeout(500);
await S(() => { const s = window.strings, m = s.gameBoard.chips.find(c => c.userData.phrase.key === "cards"); s.gameBoard.poke(m.localToWorld(new m.position.constructor())); });
await page.waitForTimeout(800);
console.log("cards open:", await S(() => window.strings.storyCards.group.visible));
await page.screenshot({ path: `${out}/cards1.png` });
const pokeTab = (id) => S((id) => { const s = window.strings, b = s.storyCards; b.cool = 0; const m = b.tabs.find(t => t.userData.tab === id); return b.poke(m.localToWorld(new m.position.constructor())); }, id);
const pokeItem = (id) => S((id) => { const s = window.strings, b = s.storyCards; b.cool = 0; const m = b.items.find(t => t.userData.id === id); return b.poke(m.localToWorld(new m.position.constructor())); }, id);
await pokeItem("troll"); await page.waitForTimeout(300);                         // villain tab is first
await pokeTab("captive"); await page.waitForTimeout(300); await pokeItem("none");
await pokeTab("challenge"); await page.waitForTimeout(300); await pokeItem("befriend");
await pokeTab("twist"); await page.waitForTimeout(300); await pokeItem("moon");
console.log("chosen:", JSON.stringify(await S(() => window.strings.storyCards.active)));
await page.screenshot({ path: `${out}/cards2.png` });
await pokeTab("go");
await waitFor(() => window.strings.book.open, null, 30000);
console.log("book:", await S(() => window.strings.book.chapter.title), "|", await S(() => window.strings.book.chapter.pages[1]));
await S(() => window.strings.book.skipAll());
await waitFor(() => window.strings.show.state === "intro" || window.strings.show.state === "act", null, 60000);
await page.waitForTimeout(1500);
console.log("stage:", JSON.stringify(await S(() => ({ set: window.strings.chapter.set, guest: window.strings.guestId, mode: window.strings.mode.id, acts: window.strings.show.scene.acts.map(a => a.goal) }))));
console.log(logs.join("\n") || "no errors");
await browser.close();
