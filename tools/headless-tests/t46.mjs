import { chromium } from "playwright-core";
import fs from "node:fs";
const out = process.argv[2];
const base = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64`;
const exe = fs.readdirSync(base).find(f => f.endsWith(".app"));
const browser = await chromium.launch({ executablePath: `${base}/${exe}/Contents/MacOS/${exe.replace(".app","")}`, args: ["--use-angle=swiftshader","--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1360, height: 860 } });
const logs = [];
page.on("pageerror", e => logs.push("pageerror " + e.message + " " + (e.stack || "").split("\n")[1]));
page.on("console", m => { if (m.type() === "error" && !m.text().includes("Failed to load resource")) logs.push(m.text()); });
const S = (fn, a) => page.evaluate(fn, a);
const waitFor = (fn, a, ms = 120000) => page.waitForFunction(fn, a, { timeout: ms }).catch(() => "timeout");
await page.addInitScript(() => localStorage.clear());
await page.goto("http://localhost:8095/");
await page.waitForSelector("#mystory", { timeout: 90000 });
await page.click("#mystory");
await page.waitForTimeout(500);
await page.click('#storymaker .card[data-s="villain"][data-id="pirate"]');
await page.click('#storymaker .card[data-s="who"][data-id="marlo"]');
await page.click('#storymaker .card[data-s="twist"][data-id="moon"]');
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/pick1.png` });
await page.click("#storymaker .go");
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/pick2-preview.png` });
await page.click("#storymaker .go");
await waitFor(() => window.strings.book.open, null, 30000);
console.log("started:", await S(() => ({ title: window.strings.book.chapter.title, set: window.strings.book.chapter.set, guest: window.strings.book.chapter.guest, captive: window.strings.book.chapter.captive, twist: window.strings.book.chapter.twist })));
await S(() => window.strings.book.skipAll());
await waitFor(() => window.strings.show.state === "intro" || window.strings.show.state === "act", null, 60000);
console.log("mode:", await S(() => window.strings.mode.id), "acts:", await S(() => window.strings.show.scene.acts.map(a => a.task?.type || a.check).join(" > ")));
// every conflict builds
const all = await S(async () => { const m = await import("/src/storypicker.js"); const sm = await import("/src/storymaker.js"); const out = []; for (const conflict of ["rescue", "duel", "treasure", "outsmart", "befriend"]) for (const villain of ["marlo", "clank", "troll", "pirate", "wizard"]) { const st = sm.buildStory(m.storyFromPicks({ conflict, who: "princess", villain, twist: "none" })); const pv = m.previewOf(st); out.push(`${conflict}/${villain}: ${st.acts.length} acts — ${pv.acts[1].text}`); } return out; });
console.log(all.slice(0, 25).join("\n"));
console.log(logs.slice(0, 8).join("\n") || "no errors");
await browser.close();
