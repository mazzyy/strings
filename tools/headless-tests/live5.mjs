import { chromium } from "playwright-core";
import fs from "node:fs";
const base = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64`;
const exe = fs.readdirSync(base).find(f => f.endsWith(".app"));
const browser = await chromium.launch({ executablePath: `${base}/${exe}/Contents/MacOS/${exe.replace(".app","")}`, args: ["--use-angle=swiftshader","--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errs = [], bad = [];
page.on("pageerror", e => errs.push(e.message));
page.on("console", m => { if (m.type() === "error" && !m.text().includes("Failed to load resource")) errs.push(m.text()); });
page.on("response", r => { if (r.status() >= 400 && !r.url().includes("/api/")) bad.push(r.status() + " " + r.url()); });
const S = (fn, a) => page.evaluate(fn, a);
await page.goto("https://mazzyy.github.io/strings/");
await page.waitForSelector("#begin", { timeout: 90000 });
const menu = await S(() => [...document.querySelectorAll(".open button")].map(b => b.textContent));
await page.click("#begin");
await page.waitForFunction(() => window.strings?.book.open, null, { timeout: 30000 });
const book = await S(() => window.strings.book.chapter.id);
await page.click("#storybook .skip");
await S(() => { const s = window.strings; s.raiseCurtain(); s.renderer.__r = s.renderer.render; s.renderer.render = () => {}; });
await page.waitForTimeout(2000);
const info = await S(() => { const s = window.strings; return { chapters: s.storyMap.places.length, voices: Object.keys(s.narrator.manifest).length, unbound: !!s.unbound, freeKnob: true }; });
await S(() => { const s = window.strings; s.storyMap.state.unlocked = 7; s.changeScene(s.storyMap.places.find(p => p.id === "sky")); });
await page.waitForFunction(() => window.strings.book.open && window.strings.book.chapter.id === "sky", null, { timeout: 60000 });
await S(() => window.strings.book.finish());
await page.waitForFunction(() => window.strings.sets.current === "sky", null, { timeout: 60000 });
await page.keyboard.press("u");
await page.waitForFunction(() => window.strings.unbound.state !== "off", null, { timeout: 30000 });
console.log(JSON.stringify({ menu, firstBook: book, ...info, skySet: await S(() => window.strings.sets.current), unboundState: await S(() => window.strings.unbound.state), errors: errs.slice(0, 5), failed: bad.slice(0, 5) }));
await browser.close();
