import { chromium } from "playwright-core";
import fs from "node:fs";
const base = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64`;
const exe = fs.readdirSync(base).find(f => f.endsWith(".app"));
const browser = await chromium.launch({ executablePath: `${base}/${exe}/Contents/MacOS/${exe.replace(".app","")}`, args: ["--use-angle=swiftshader","--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errs = [], bad = [];
page.on("pageerror", e => errs.push(e.message));
page.on("console", m => { if (m.type() === "error" && !m.text().includes("Failed to load resource")) errs.push(m.text()); });
page.on("response", r => { if (r.status() >= 400 && !r.url().includes("/api/")) bad.push(r.status() + " " + r.url()); });
await page.goto("https://mazzyy.github.io/strings/");
await page.waitForSelector("#begin", { timeout: 90000 });
await page.click("#begin");
await page.waitForFunction(() => window.strings?.book.open, null, { timeout: 30000 });
const a = await page.evaluate(() => ({ book: window.strings.book.open, voices: Object.keys(window.strings.narrator.manifest).length }));
await page.click("#storybook .skip");
await page.evaluate(() => window.strings.raiseCurtain());
await page.waitForFunction(() => window.strings.show.state === "intro", null, { timeout: 90000 });
await page.evaluate(() => { const s = window.strings; s.storyMap.state.unlocked = 6; s.changeScene(s.storyMap.places.find(p => p.id === "tower")); });
await page.waitForFunction(() => window.strings.book.open, null, { timeout: 30000 });
await page.waitForTimeout(1200);
await page.screenshot({ path: process.argv[2] + "/live-book-tower.png" });
await page.evaluate(() => window.strings.book.finish());
await page.waitForFunction(() => window.strings.guestId === "clank" && window.strings.show.state === "act", null, { timeout: 120000 }).catch(() => {});
const b = await page.evaluate(() => ({ chapter: window.strings.chapter.title, guest: window.strings.guestId, task: !!window.strings.currentTask, princess: window.strings.princessDrv.state }));
console.log(JSON.stringify({ start: a, tower: b, errors: errs.slice(0, 5), failed: bad.slice(0, 5) }));
await browser.close();
